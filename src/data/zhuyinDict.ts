/**
 * Given a Traditional Chinese word, returns an array of Zhuyin strings aligned to characters.
 * Preserves existing syllables where available when editing character-by-character.
 */
export function lookupZhuyinForWord(word: string, previousZhuyin: string[] = []): string[] {
  const chars = Array.from(word.trim());
  if (chars.length === 0) return [];

  const exactWord = WORD_ZHUYIN_DICT[word.trim()];
  if (exactWord && exactWord.length === chars.length) {
    return exactWord;
  }

  return chars.map((ch, idx) => {
    if (CHAR_ZHUYIN_DICT[ch]) {
      return CHAR_ZHUYIN_DICT[ch];
    }
    if (previousZhuyin[idx]) {
      return previousZhuyin[idx];
    }
    return '';
  });
}

